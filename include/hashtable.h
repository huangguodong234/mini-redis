/* ============================================================
 * 一、value 存储方式的设计权衡
 * ============================================================
 *
 * 1. 从内存分配开销来看：
 *    我的实现：char *value 是指针类型。先要申请一次节点的内存，存数据时
 *            用 strdup，strdup 会调用 malloc 又是一次内核态切换。
 *            实现一次插入要两次内存分配的开销。
 *
 *    Redis 的实现：union 共用体类型。申请一次 dictEntry 结构体的内存时
 *               把 union 的内存一起申请了。只有一次内存分配的开销。
 *
 * 2. 从避免重复内存分配来看：
 *    我的实现：申请了两次内存，增加了内存管理的负担。
 *    Redis 的实现：只申请了一块内存，既解决了节点本身的需要，也为小的
 *                整数值准备好了"车位"。
 *
 * 3. 从消除不必要的类型转换来看：
 *    我的实现：如果进来的数据不是字符串类型，还要再申请一块内存，
 *            来做类型转换后的存储。
 *    Redis 的实现：不管是什么类型的都可以存，不用做类型转换。
 *                因为 union 可以设置所有的类型。
 */


/* ============================================================
 * 三、dictType / dictEntry / dict 三层架构
 * ============================================================
 *
 * 之后通过 dictType 函数告诉调用者，怎么处理数据，包括怎么算哈希，
 * 怎么复制 key/value，怎么比大小，键值不用了怎么销毁，什么时候扩容
 * 哈希表，什么时候清理旧的哈希表，申请的空间没用完时怎么办。
 *
 * dictType   — 接口，是操作手册（C 语言实现多态的经典手法——函数指针表）
 * dictEntry  — 数据节点（Data Object），只存数据，没有任何行为
 * dict       — 持有数据节点 + 持有接口，把两者粘在一起
 *
 * 关于 dictType（字典的定制说明书）：
 *   把"怎么处理数据"从核心逻辑中抽离，做成配置项，方便后续优化。
 *
 *   动态调用：只存函数指针（哈希、比较、销毁等）。核心代码写死一套，
 *            传入不同的 dictType，就能动态调用对应数据类型（如 SDS、
 *            整数）的处理函数。
 *
 *   扩容控制：提供是否允许扩容、搬家前后的回调钩子，让底层扩容过程可控。
 */

/* ============================================================
 * 四、扩容策略的区别
 * ============================================================
 *
 * 我的 mini-redis：扩容时一次性把旧表数据全部搬到新表。
 *
 * Redis：渐进式扩容（rehash），在每次添加/删除/查找时只搬一个桶。
 *
 * 为什么 Redis 不用一次性搬迁？
 *   - 当数据量很大时（千万级 key），一次性搬迁耗时几百毫秒甚至秒级，
 *     这期间 Redis 无法处理任何请求，造成严重延迟。
 *   - 渐进式搬迁把耗时摊平到每次操作里，单次搬迁微秒级，客户端无感。
 */

/* ============================================================
 * 五、插入/查找/删除操作的区别
 * ============================================================
 *
 * 插入 key 操作的区别：
 *   我：只有一张哈希表，直接插入。
 *   Redis：有两张表。rehash 期间新 key 直接插入新表（ht_table[1]），
 *   这样旧表只减不增，保证最终能搬空。如果插入旧表，搬迁时又要多搬
 *   一个节点。
 *
 * 查找/删除操作的区别：
 *   我：只查一张表。
 *   Redis：rehash 期间必须遍历两张表，因为数据可能还在旧表没搬完。
 *   遍历旧表时，索引小于 rehashidx 的桶已被搬迁，可以直接跳过。
 *
 *
//每次 dictAdd / dictFind / dictDelete
        │
        │  用户执行 GET key，假设 key 哈希到桶 #5
        │
        ▼
_dictRehashStepIfNeeded(d, 5)       ← 入口：每次操作都调，visitedIdx = 5
        │
        ├── 没在 rehash 或被暂停？ → 直接返回
        │
        └── 正在 rehash →
                │
                ├──────────────────────────────────────────────
                │  判断：桶 #5 还没搬过（5 >= rehashidx）且非空？
                │
                │    是 → 路径 A：搬桶 #5（当前访问的桶）
                │         │
                │         │  ★ 缓存友好：桶 #5 的数据刚才被 GET 请求访问过，
                │         │    已经在 CPU 缓存里，搬迁时读 key/next 很快（纳秒级）
                │         │
                │         └── _dictBucketRehash(d, 5)
                │                 │
                │                 └── rehashEntriesInBucketAtIndex(d, 5)
                │                         │
                │                         ├── 有 value → 头插
                │                         └── 无 value → 分情况处理（新桶状态（空/不空），旧节点形式（key 裸指针/dictEntryNoValue））
                │
                │    否 → 路径 B：搬 rehashidx 指向的下一个非空桶
                │         │
                │         │  ★ 缓存不友好：这个桶当前请求没碰过，
                │         │    数据大概率不在缓存里，需要从主内存加载（几十纳秒）
                │         │
                │         └── dictRehash(d, 1)          ← 函数三：搬一个桶
                │                 │
                │                 ├── 跳过空桶（最多 10 个）
                │                 │
                │                 ├── 找到非空桶 → rehashEntriesInBucketAtIndex
                │                 │       ← 函数四：搬桶内全部节点
                │                 │
                │                 └── rehashidx++
                │
                └──────────────────────────────────────────────
                        │
                        └── ht_used[0] == 0？
                            是 → dictCheckRehashingCompleted  ← 函数五：收尾
                            否 → 下次继续


只有插入时额外触发扩容检查：
dictAdd → _dictExpandIfNeeded  ← 函数一：检查负载因子
              │
              └── 满了 → _dictResize  ← 函数二：创建新表，rehashidx = 0
            
*/

/* ============================================================
 * 六、极致省内存的设计
 * ============================================================
 *
 * Redis 有三层存储策略（从省到费）：
 *   1. 空桶直存：key 指针直接塞进桶位，连 entry 都不分配
 *      （通过指针低位标记区分类型）
 *   2. 轻量节点：碰撞时分配 dictEntryNoValue，只有 key + next，
 *      省掉 union v（8 字节）
 *   3. 完整节点：普通字典模式，分配完整 dictEntry
 *
 * 策略选择由 dictType 中的位域标志控制（no_value、keys_are_odd），
 * 只占 1 bit。成千上万个同类字典实例共享同一个 dictType，标志位
 * 只需存一份。这是类级别的内存优化——把元数据从"每个实例存一份"
 * 提升到"每种类型存一份"。
 *
 * 通过指针低 3 位标记（ENTRY_PTR_MASK）区分桶里存的是哪种：
 *   000 → 普通 dictEntry
 *   001 → 奇数地址的 key 指针
 *   010 → 偶数地址的 key 指针
 *   100 → dictEntryNoValue 节点
 */

/*  核心差异：
*       void *key + dictType 多态 vs sds key 硬编码（已用 SDS，但类型写死）
*       union v 内联存储 vs sds value 指针（已用 SDS，但仍是独立指针）
*       渐进式 rehash（双表 + rehashidx）vs 一次性搬迁
*       8.0 特有：ht_size_exp 指数存大小
*/

// 哈希表节点（链表节点）；key/value 都是 sds，由调用方（storage）拷贝传入，
// 哈希表接管所有权并负责最终释放
typedef struct HashNode{
    sds key;
    sds value;
    struct HashNode *next;    // 指向下一个节点
}HashNode;

//哈希表结构体
typedef struct{
    HashNode **buckets;  // 桶数组（指针数组）
    int size;            // 当前存储的键值对个数
    int capacity;         // 桶的数量
}HashTable;

// 创建哈希表，initial_capacity 是初始桶数
HashTable *hashtable_create(int initial_capacity);

//插入或更新键值对-SET命令
// key/value 为 sds，由本表接管所有权（存储后由 hashtable_free/del 释放）
void hashtable_set(HashTable *ht,sds key,sds value);

//查找 key，返回内部 value 指针（sds，本质 char*，外部不要 free；找不到返回 NULL）-GET命令
// key 为查询用 sds，只读不接管
// ⚠ 返回的是哈希表内部活引用（借用）：调用方不得 free，且其有效性依赖"调用期间
//   表不被改"。storage 层的 storage_get 会在此基础上 sdsdup 成可拥有快照再外传。
char *hashtable_get(HashTable *ht,sds key);

// 删除 key，返回 1 成功，0 不存在-DEL命令（key 只读不接管）
int hashtable_del(HashTable *ht,sds key);

//销毁哈希表，释放所有内存
void hashtable_free(HashTable*ht);

#endif
